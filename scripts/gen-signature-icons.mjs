const PRESETS = ['4f46e5', '0ea5e9', '10b981', 'ef4444', 'f59e0b', '8b5cf6', '0f172a', 'db2777', '475569'];

function contactSvg(d, hex) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24"><path fill="#${hex}" d="${d}"/></svg>`;
}
function socialSvg(d, bg) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64" viewBox="0 0 64 64">` +
    `<rect width="64" height="64" rx="15" fill="${bg}"/>` +
    `<g transform="translate(14,14) scale(1.5)" fill="#ffffff"><path d="${d}"/></g></svg>`;
}

async function run() {
  await mkdir(OUT, { recursive: true });
  let n = 0;

  for (const [name, info] of Object.entries(SOCIAL)) {
    await sharp(Buffer.from(socialSvg(info.d, info.bg))).png().toFile(path.join(OUT, `social-${name}.png`));
    n++;
  }

  for (const hex of PRESETS) {
    for (const [name, d] of Object.entries(CONTACT)) {
      // render @3x (48px) cho sắc nét, hiển thị 16px trong chữ ký
      await sharp(Buffer.from(contactSvg(d, hex)))
        .resize(48, 48)
        .png()
        .toFile(path.join(OUT, `${name}-${hex}.png`));
      n++;
    }
  }

  console.log(`Đã sinh ${n} icon PNG vào public/signature-icons/`);
}

run().catch((e) => { console.error(e); process.exit(1); });
